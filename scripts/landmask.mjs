// Builds src/data/land.ts: a 2-degree land/sea bitmap for the pixel globe, from Natural Earth 110m (world-atlas).
// Run once when changing resolution: node scripts/landmask.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';

const STEP = 2; // degrees per cell
const W = 360 / STEP;
const H = 180 / STEP;
const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-110m.json', 'utf8'));
const land = feature(topo, topo.objects.land);
const rings = land.features.flatMap((f) => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates));

// Even-odd ray casting over every ring of every polygon (holes included).
function inside(lon, lat) {
  let hit = false;
  for (const poly of rings)
    for (const ring of poly)
      for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
        const [xi, yi] = ring[i];
        const [xj, yj] = ring[j];
        if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
      }
  return hit;
}

const bits = new Uint8Array(Math.ceil((W * H) / 8));
let count = 0;
for (let y = 0; y < H; y++)
  for (let x = 0; x < W; x++) {
    const lat = 90 - (y + 0.5) * STEP;
    const lon = -180 + (x + 0.5) * STEP;
    if (inside(lon, lat)) {
      const i = y * W + x;
      bits[i >> 3] |= 1 << (i & 7);
      count++;
    }
  }

writeFileSync(
  'src/data/land.ts',
  `// Generated by scripts/landmask.mjs from Natural Earth 110m land (public domain). ${count} land cells.\n` +
    `export const LAND_STEP = ${STEP};\nexport const LAND_W = ${W};\nexport const LAND_H = ${H};\n` +
    `export const LAND_BITS = '${Buffer.from(bits).toString('base64')}';\n`,
);
console.log(`land.ts: ${W}x${H}, ${count} land cells`);
