// One entry per place for the globe and "Surprise me": repeated places (Kyoto in spring and autumn) appear once.
const seen = new Set<string>();
export const PLACES: Destination[] = THEMES.flatMap((th) => th.destinations).filter((d) => {
  const key = `${d.name}|${d.country}`;
  if (seen.has(key)) return false;
  seen.add(key);
  return true;
});

export const SURPRISE: Theme = { id: 'surprise', name: 'Surprise me', when: 'Any time', destinations: PLACES };

export const ALL_THEMES = [...THEMES, SURPRISE];

export const findTheme = (id: string) => ALL_THEMES.find((x) => x.id === id);
export const findDestination = (themeId: string, destId: string) => findTheme(themeId)?.destinations.find((x) => x.id === destId);
/** The first real theme a destination belongs to (for places picked from the globe or Surprise me). */
export const themeOf = (d: Destination) => THEMES.find((x) => x.destinations.some((y) => y.id === d.id));
